  return next;
end;
$$;

-- Cleanup, step 1 (service role only): candidates become `deleting` and are returned with their
-- object names. The page row is locked and references are re-checked, so an asset a concurrent
-- save or publish just started using is never claimed. Safe to call again at any time.
create function public.claim_media_cleanup(p_limit integer default 50)
returns table (media_id uuid, object_names text[])
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_row record;
begin
  for v_row in
    select m.id, m.profile_id
    from public.media_assets m
    where m.status = 'deleting'
      or (m.status in ('pending', 'failed') and m.created_at < now() - private.media_pending_grace())
      or (m.status = 'ready' and m.created_at < now() - private.media_orphan_grace()
          and not private.media_is_referenced(m.id, m.profile_id))
      or exists (select 1 from public.profiles p where p.id = m.profile_id and p.purge_after < now())
    order by m.created_at
    limit greatest(1, least(coalesce(p_limit, 50), 200))
  loop
    perform 1 from public.profiles p where p.id = v_row.profile_id for update;
    update public.media_assets m
    set status = 'deleting'
    where m.id = v_row.id
      and (
        m.status in ('deleting', 'pending', 'failed')
        or exists (select 1 from public.profiles p where p.id = m.profile_id and p.purge_after < now())
        or not private.media_is_referenced(m.id, m.profile_id)
      );
    if found then
      media_id := v_row.id;
      select array_agg(v_row.id::text || '/' || (v ->> 'w') || '.webp' order by (v ->> 'w')::integer) into object_names
      from public.media_assets m, jsonb_array_elements(m.variants) v
      where m.id = v_row.id;
      return next;
    end if;
  end loop;
end;
$$;

-- Cleanup, step 2 (service role only): the objects are gone, forget the rows.
create function public.finish_media_cleanup(p_media_ids uuid[])
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  delete from public.media_assets m where m.id = any (p_media_ids) and m.status = 'deleting';
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

