-- True while the page's draft or any retained publication of the page points at the asset.
-- Computed from the documents, so there is no second source of truth to drift.
create function private.media_is_referenced(p_media_id uuid, p_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
      select 1 from public.profiles p
      where p.id = p_profile_id
        and (p.avatar_path = p_media_id::text
          or p.blocks @> jsonb_build_array(jsonb_build_object('type', 'image', 'mediaId', p_media_id::text)))
    )
    or exists (
      select 1 from public.profile_publications pp
      where pp.profile_id = p_profile_id
        and (pp.document ->> 'avatarPath' = p_media_id::text
          or pp.document -> 'blocks' @> jsonb_build_array(jsonb_build_object('type', 'image', 'mediaId', p_media_id::text)))
    );
$$;

-- Bytes that count against the quota: live assets that are referenced or still inside the grace
-- period. Orphans stop counting as soon as they are cleanup candidates.
create function private.workspace_media_bytes(p_workspace_id uuid)
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(sum(m.bytes), 0)::bigint
  from public.media_assets m
  where m.workspace_id = p_workspace_id
    and m.status in ('pending', 'ready')
    and (m.created_at > now() - private.media_orphan_grace() or private.media_is_referenced(m.id, m.profile_id));
$$;

-- Variant plan (mirror of modules/media/policy.ts planVariants): avatars are the three squares;
-- images keep 448/896/1344 below the master width plus the master itself, never enlarged.
create function private.media_variants_are_valid(p_kind public.media_kind, p_width integer, p_height integer, p_variants jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_widths integer[];
  v_expected integer[];
begin
  if p_kind is null or p_width is null or p_height is null
    or p_variants is null or jsonb_typeof(p_variants) <> 'array'
    or jsonb_array_length(p_variants) not between 1 and 4 then
    return false;
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_variants) v
    where jsonb_typeof(v) <> 'object'
      or (select array_agg(k order by k collate "C") from jsonb_object_keys(v) k) is distinct from array['bytes', 'h', 'w']
      or jsonb_typeof(v -> 'w') <> 'number' or (v ->> 'w') !~ '^[1-9][0-9]{0,3}$'
      or jsonb_typeof(v -> 'h') <> 'number' or (v ->> 'h') !~ '^[1-9][0-9]{0,3}$'
      or jsonb_typeof(v -> 'bytes') <> 'number' or (v ->> 'bytes') !~ '^[1-9][0-9]{0,6}$'
      or (v ->> 'bytes')::integer > 2097152
  ) then
    return false;
  end if;

  select array_agg((v ->> 'w')::integer order by (v ->> 'w')::integer) into v_widths from jsonb_array_elements(p_variants) v;
  if p_kind = 'avatar' then
    v_expected := array[96, 192, 288];
    if p_width <> 288 or p_height <> 288
      or exists (select 1 from jsonb_array_elements(p_variants) v where v ->> 'w' <> v ->> 'h') then
      return false;
    end if;
  else
    if p_width not between 200 and 1344 or p_height not between 100 and 4096
      or p_width > 3 * p_height or p_height > 3 * p_width then
      return false;
    end if;
    v_expected := array(select w from unnest(array[448, 896, 1344]) w where w < p_width order by w) || p_width;
  end if;
  if v_widths is distinct from v_expected then
    return false;
  end if;
  -- The master variant carries the declared dimensions.
  return exists (
    select 1 from jsonb_array_elements(p_variants) v
    where (v ->> 'w')::integer = p_width and (v ->> 'h')::integer = p_height
  );
end;
$$;

-- Canonical text the application signs (mirror of modules/media/attestation.ts registerPayload).
create function private.media_register_payload(p_media_id uuid, p_profile_id uuid, p_kind public.media_kind, p_width integer, p_height integer, p_variants jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select 'register:' || p_media_id::text || ':' || p_profile_id::text || ':' || p_kind::text || ':' || p_width::text || 'x' || p_height::text || ':'
    || (select string_agg((v ->> 'w') || 'x' || (v ->> 'h') || 'x' || (v ->> 'bytes'), ',' order by (v ->> 'w')::integer)
        from jsonb_array_elements(p_variants) v);
$$;

-- Shared secret between the application server (MEDIA_SIGNING_SECRET) and the database. Stored in
-- Supabase Vault under this name by a deploy step, never in a migration.
create function private.media_signing_secret()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select s.decrypted_secret from vault.decrypted_secrets s where s.name = 'media_signing_secret' limit 1;
$$;

-- HMAC-SHA256 attestation (ADR 0009): proves the caller is the application server that validated
-- and re-encoded the bytes, not just somebody with a valid session.
create function private.media_signature_is_valid(p_payload text, p_signature text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_secret text := private.media_signing_secret();
  v_expected text;
begin
  if v_secret is null or char_length(v_secret) < 32 then
    raise exception 'media signing is not configured' using errcode = 'LK090';
  end if;
  if p_payload is null or p_signature is null or p_signature !~ '^[0-9a-f]{64}$' then
    return false;
  end if;
  v_expected := encode(extensions.hmac(convert_to(p_payload, 'UTF8'), convert_to(v_secret, 'UTF8'), 'sha256'), 'hex');
  -- Compare digests so the time taken does not depend on where the two strings differ.
  return extensions.digest(v_expected, 'sha256') = extensions.digest(p_signature, 'sha256');
end;
$$;

-- Step 1 of an upload: the server registers what it validated. Called as the signed-in user.
create function public.register_media_asset(
  p_media_id uuid,
  p_profile_id uuid,
  p_kind public.media_kind,
  p_width integer,
  p_height integer,
  p_variants jsonb,
  p_signature text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_profile public.profiles;
  v_role public.workspace_role;
  v_bytes bigint;
  v_limit bigint;
  v_recent integer;
begin
  if v_uid is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select p.* into v_profile from public.profiles p where p.id = p_profile_id and p.deleted_at is null;
  if not found then
    raise exception 'profile not found' using errcode = 'P0002';
  end if;
  v_role := private.workspace_role(v_profile.workspace_id);
  if v_role is null then
    raise exception 'profile not found' using errcode = 'P0002';
  end if;
  if not private.workspace_is_writable(v_profile.workspace_id) then
    raise exception 'workspace does not accept changes' using errcode = '42501';
  end if;
  -- Matrix: profile.edit_content = owner, admin, editor (modules/identity/permissions.ts).
  if v_role not in ('owner', 'admin', 'editor') then
    raise exception 'role cannot upload media' using errcode = '42501';
  end if;

  if p_media_id is null or not private.media_variants_are_valid(p_kind, p_width, p_height, p_variants) then
    raise exception 'invalid media description' using errcode = '22023';
  end if;
  if not private.media_signature_is_valid(
    private.media_register_payload(p_media_id, p_profile_id, p_kind, p_width, p_height, p_variants), p_signature) then
    raise exception 'upload was not validated by the application' using errcode = 'LK060';
  end if;

  -- Lock the workspace so concurrent uploads cannot both pass the quota.
  perform 1 from public.workspaces w where w.id = v_profile.workspace_id for update;

  select count(*) into v_recent
  from public.media_assets m
  where m.workspace_id = v_profile.workspace_id and m.created_at > now() - interval '1 hour';
  if v_recent >= 60 then
    raise exception 'too many uploads' using errcode = 'LK061';
  end if;

  select sum((v ->> 'bytes')::bigint) into v_bytes from jsonb_array_elements(p_variants) v;
  v_limit := coalesce(private.entitlement_int(v_profile.workspace_id, 'storage_mb'), 0)::bigint * 1048576;
  if private.workspace_media_bytes(v_profile.workspace_id) + v_bytes > v_limit then
    raise exception 'storage quota reached' using errcode = 'LK010', detail = 'storage_mb';
  end if;

  insert into public.media_assets (id, workspace_id, profile_id, kind, status, width, height, bytes, variants, created_by)
  values (p_media_id, v_profile.workspace_id, v_profile.id, p_kind, 'pending', p_width, p_height, v_bytes::integer, p_variants, v_uid);
end;
$$;

-- Step 3 of an upload: every registered variant is in the bucket with the registered size.
create function public.activate_media_asset(p_media_id uuid, p_signature text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_asset public.media_assets;
  v_stored integer;
begin
  if v_uid is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  select m.* into v_asset from public.media_assets m where m.id = p_media_id for update;
  if not found or v_asset.created_by is distinct from v_uid then
    raise exception 'media not found' using errcode = 'P0002';
  end if;
  if v_asset.status = 'ready' then
    return;
  end if;
  if v_asset.status <> 'pending' then
    raise exception 'media cannot be activated' using errcode = '42501';
  end if;
  if not private.media_signature_is_valid('activate:' || p_media_id::text, p_signature) then
    raise exception 'upload was not validated by the application' using errcode = 'LK060';
  end if;

  select count(*) into v_stored
  from jsonb_array_elements(v_asset.variants) v
  join storage.objects o
    on o.bucket_id = 'media'
   and o.name = p_media_id::text || '/' || (v ->> 'w') || '.webp'
   and o.metadata ->> 'size' = v ->> 'bytes';
  if v_stored <> jsonb_array_length(v_asset.variants) then
    raise exception 'stored objects do not match the registration' using errcode = 'LK062';
  end if;

  update public.media_assets set status = 'ready', activated_at = now() where id = p_media_id;
end;
$$;

-- The uploader abandons its own pending asset; cleanup removes whatever was written.
create function public.fail_media_asset(p_media_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  update public.media_assets
  set status = 'failed'
  where id = p_media_id and created_by = (select auth.uid()) and status = 'pending';
end;
$$;

-- "Espaço usado" for the editor.
create function public.workspace_storage_usage(p_workspace_id uuid)
returns table (used_bytes bigint, limit_bytes bigint)
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
begin
  if (select auth.uid()) is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  if p_workspace_id is null or p_workspace_id not in (select private.member_workspace_ids()) then
    raise exception 'workspace not found' using errcode = 'P0002';
