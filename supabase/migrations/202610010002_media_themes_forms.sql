    when 'form' then jsonb_build_object('id', p_block ->> 'id', 'type', 'form', 'title', p_block ->> 'title', 'fields', p_block -> 'fields', 'buttonLabel', p_block ->> 'buttonLabel', 'consentText', p_block ->> 'consentText', 'consentRequired', p_block -> 'consentRequired')
  end;
$$;

-- `theme` is present only when the page has one, so a page without a theme publishes exactly the
-- document it published before this migration.
create or replace function private.build_publication_document(p_profile public.profiles)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'schemaVersion', 2,
    'title', p_profile.title,
    'bio', p_profile.bio,
    'avatarPath', p_profile.avatar_path,
    'blocks', coalesce((
      select jsonb_agg(private.published_block(b) order by ord)
      from jsonb_array_elements(p_profile.blocks) with ordinality as t(b, ord)
