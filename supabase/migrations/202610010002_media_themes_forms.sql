-- How long a lead is kept (provisional). Expired leads are hidden by RLS at once and deleted on the
-- next submission to the page or by the purge job (Sprint 9).
create function private.lead_retention()
returns interval
language sql
immutable
set search_path = ''
as $$ select interval '90 days' $$;

create table public.form_leads (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  -- Id of the form block in the publication the visitor saw.
  block_id text not null check (char_length(block_id) between 1 and 64),
  publication_version integer not null,
  name text check (name is null or char_length(name) between 1 and 100),
  email text check (email is null or char_length(email) between 3 and 254),
  phone text check (phone is null or phone ~ '^\+?[0-9]{8,15}$'),
  message text check (message is null or char_length(message) between 1 and 1000),
  consent_given boolean not null,
  consent_required boolean not null,
  -- The exact text the visitor saw, and its version (MD5 of the text).
  consent_text text not null check (char_length(consent_text) between 1 and 300),
  consent_version text not null check (consent_version ~ '^[0-9a-f]{32}$'),
  consented_at timestamptz,
  -- Same form and same content: used to store a retried submission only once.
  dedupe_key text not null check (dedupe_key ~ '^[0-9a-f]{32}$'),
  created_at timestamptz not null default now(),
  purge_after timestamptz not null,
  constraint form_leads_contact check (email is not null or phone is not null),
  constraint form_leads_consent_timestamp check (consent_given = (consented_at is not null)),
  constraint form_leads_required_consent check (not consent_required or consent_given)
);

create index form_leads_profile_created_idx on public.form_leads (profile_id, created_at desc);
create index form_leads_workspace_idx on public.form_leads (workspace_id);
create index form_leads_purge_after_idx on public.form_leads (purge_after);
create index form_leads_dedupe_idx on public.form_leads (profile_id, dedupe_key, created_at desc);

comment on table public.form_leads is
  'Personal data typed by visitors in a form block (ADR 0010). The page owner is the controller; the product is the operator. Never contains IP addresses. Retention: private.lead_retention() (90 days, provisional) through purge_after.';

-- Accepted submissions per visitor hash, for the rate limit only. The hash is an HMAC of the IP
-- keyed by a server secret and the day (never the raw address); rows older than a day are deleted.
create table public.form_submission_hits (
  id bigint generated always as identity primary key,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  client_hash text not null check (client_hash ~ '^([0-9a-f]{32}|direct)$'),
  created_at timestamptz not null default now()
);

create index form_submission_hits_profile_created_idx on public.form_submission_hits (profile_id, created_at desc);
create index form_submission_hits_client_idx on public.form_submission_hits (profile_id, client_hash, created_at desc);

comment on table public.form_submission_hits is
  'Rate-limit counters for form submissions (ADR 0010): page + salted daily hash of the visitor address. No raw IP. Rows are deleted after 24 hours by submit_form_lead.';

-- The only write path for visitors. Validates against the form in the LIVE publication, so a form
-- that was removed or never published accepts nothing. Answers with a status and nothing else:
--   ok               stored (or a retry of something already stored, or a filled honeypot)
--   invalid          a field is missing or malformed
--   consent_required the form requires consent and it was not given
--   rate_limited     too many submissions from this visitor or to this page
--   unavailable      no such published form at this address
create function public.submit_form_lead(
  p_slug text,
  p_block_id text,
  p_fields jsonb,
  p_consent boolean default false,
  p_honeypot text default '',
  p_client_hash text default null
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_slug text := private.normalize_slug(coalesce(p_slug, ''));
  v_profile public.profiles;
  v_document jsonb;
  v_version integer;
  v_form jsonb;
  v_field text;
  v_value text;
  v_name text;
  v_email text;
  v_phone text;
  v_message text;
  v_consent boolean := coalesce(p_consent, false);
  v_client text;
  v_dedupe text;
begin
  -- Hidden field real visitors never fill. Automated posts get the same answer as a real one.
  if btrim(coalesce(p_honeypot, '')) <> '' then
    return 'ok';
  end if;
  if not private.slug_is_well_formed(v_slug) or p_block_id is null then
    return 'unavailable';
  end if;
  if p_fields is null or jsonb_typeof(p_fields) <> 'object' or octet_length(p_fields::text) > 4096 then
    return 'invalid';
  end if;

  select p.* into v_profile
  from public.profiles p
  join public.workspaces w on w.id = p.workspace_id
  where p.slug = v_slug
    and p.deleted_at is null
    and p.live_publication_id is not null
    and w.deleted_at is null
    and w.status = 'active';
  if not found then
    return 'unavailable';
  end if;

  select pp.document, pp.version into v_document, v_version
  from public.profile_publications pp where pp.id = v_profile.live_publication_id;
  select b into v_form
  from jsonb_array_elements(case when jsonb_typeof(v_document -> 'blocks') = 'array' then v_document -> 'blocks' else '[]'::jsonb end) b
  where b ->> 'id' = p_block_id and b ->> 'type' = 'form'
  limit 1;
  if v_form is null or not private.is_valid_form_fields(v_form -> 'fields') then
    return 'unavailable';
  end if;

  -- Only the fields of the published form are read; anything else in the request is ignored.
  for v_field in select f from unnest(array['name', 'email', 'phone', 'message']) f where v_form -> 'fields' ? f loop
    v_value := case when jsonb_typeof(p_fields -> v_field) = 'string' then p_fields ->> v_field else '' end;
    if v_field = 'message' then
      v_value := btrim(regexp_replace(v_value, E'\r\n?', E'\n', 'g'), E' \t\n');
      if char_length(v_value) > 1000 or replace(v_value, E'\n', '') ~ '[[:cntrl:]]' then
        return 'invalid';
      end if;
      v_message := nullif(v_value, '');
    else
      v_value := regexp_replace(btrim(v_value, E' \t\n\r'), '\s+', ' ', 'g');
      if v_value = '' or v_value ~ '[[:cntrl:]]' then
        return 'invalid';
      end if;
      if v_field = 'name' then
        if char_length(v_value) > 100 then return 'invalid'; end if;
        v_name := v_value;
      elsif v_field = 'email' then
        v_value := lower(v_value);
        if char_length(v_value) > 254 or v_value !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then return 'invalid'; end if;
        v_email := v_value;
      else
        if char_length(v_value) > 20 or v_value !~ '^\+?[0-9[:space:]().-]+$' then return 'invalid'; end if;
        v_phone := case when v_value like '+%' then '+' else '' end || regexp_replace(v_value, '[^0-9]', '', 'g');
        if v_phone !~ '^\+?[0-9]{8,15}$' then return 'invalid'; end if;
      end if;
    end if;
  end loop;

  if coalesce((v_form ->> 'consentRequired')::boolean, true) and not v_consent then
    return 'consent_required';
  end if;

  -- One submission at a time per page, so the counters below cannot be raced.
  perform pg_advisory_xact_lock(hashtextextended('form_lead:' || v_profile.id::text, 0));

  delete from public.form_submission_hits h where h.profile_id = v_profile.id and h.created_at < now() - interval '1 day';
  delete from public.form_leads l where l.profile_id = v_profile.id and l.purge_after < now();

  -- Retry safety: the same content to the same form within 10 minutes is stored once.
  v_dedupe := md5(v_profile.id::text || ':' || p_block_id || ':' || coalesce(v_name, '') || E'\x1f' || coalesce(v_email, '') || E'\x1f' || coalesce(v_phone, '') || E'\x1f' || coalesce(v_message, ''));
  if exists (
    select 1 from public.form_leads l
    where l.profile_id = v_profile.id and l.dedupe_key = v_dedupe and l.created_at > now() - interval '10 minutes'
  ) then
    return 'ok';
  end if;

  -- A caller without a hash from the application (a direct API call) shares one bucket.
  v_client := case when p_client_hash ~ '^[0-9a-f]{32}$' then p_client_hash else 'direct' end;
  if (select count(*) from public.form_submission_hits h
      where h.profile_id = v_profile.id and h.client_hash = v_client and h.created_at > now() - interval '10 minutes') >= 5
    or (select count(*) from public.form_submission_hits h
        where h.profile_id = v_profile.id and h.created_at > now() - interval '1 hour') >= 60 then
    return 'rate_limited';
  end if;

  insert into public.form_submission_hits (profile_id, client_hash) values (v_profile.id, v_client);
  insert into public.form_leads (
    workspace_id, profile_id, block_id, publication_version, name, email, phone, message,
    consent_given, consent_required, consent_text, consent_version, consented_at, dedupe_key, purge_after)
  values (
    v_profile.workspace_id, v_profile.id, p_block_id, v_version, v_name, v_email, v_phone, v_message,
    v_consent, coalesce((v_form ->> 'consentRequired')::boolean, true), v_form ->> 'consentText', md5(v_form ->> 'consentText'),
    case when v_consent then now() end, v_dedupe, now() + private.lead_retention());
  return 'ok';
end;
$$;

-- Shared authorization for owner-side lead commands: owners and admins of a writable workspace.
create function private.authorize_lead_admin(p_workspace_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role public.workspace_role;
begin
  if (select auth.uid()) is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  v_role := private.workspace_role(p_workspace_id);
  if v_role is null then
    raise exception 'not found' using errcode = 'P0002';
  end if;
  if not private.workspace_is_writable(p_workspace_id) then
    raise exception 'workspace does not accept changes' using errcode = '42501';
  end if;
  -- Matrix: leads.delete and leads.export = owner, admin (modules/identity/permissions.ts).
  if v_role not in ('owner', 'admin') then
    raise exception 'only owners and admins manage leads' using errcode = '42501';
  end if;
end;
$$;

create function public.delete_form_lead(p_lead_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lead public.form_leads;
begin
  if (select auth.uid()) is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  select l.* into v_lead from public.form_leads l where l.id = p_lead_id for update;
  if not found or private.workspace_role(v_lead.workspace_id) is null then
    raise exception 'lead not found' using errcode = 'P0002';
  end if;
  perform private.authorize_lead_admin(v_lead.workspace_id);

  delete from public.form_leads where id = p_lead_id;
  -- The trail records that a deletion happened, never the lead's content.
  perform private.write_audit_event(v_lead.workspace_id, 'lead.deleted', 'profile', v_lead.profile_id, jsonb_build_object('count', 1));
end;
$$;

-- Called by the application right before it hands a CSV to the person.
create function public.record_lead_export(p_profile_id uuid, p_count integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_workspace_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  select p.workspace_id into v_workspace_id from public.profiles p where p.id = p_profile_id and p.deleted_at is null;
  if not found or private.workspace_role(v_workspace_id) is null then
    raise exception 'profile not found' using errcode = 'P0002';
  end if;
  perform private.authorize_lead_admin(v_workspace_id);
  perform private.write_audit_event(v_workspace_id, 'lead.exported', 'profile', p_profile_id,
    jsonb_build_object('count', greatest(0, coalesce(p_count, 0))));
