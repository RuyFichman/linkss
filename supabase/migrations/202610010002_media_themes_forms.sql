-- Closed token set: two lowercase hex colors and four enumerations, nothing else.
create function private.is_valid_theme(p_theme jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    jsonb_typeof(p_theme) = 'object'
    and (select array_agg(k order by k collate "C") from jsonb_object_keys(p_theme) k)
      = array['background', 'button', 'buttonStyle', 'corners', 'font', 'spacing']
    and jsonb_typeof(p_theme -> 'background') = 'string' and p_theme ->> 'background' ~ '^#[0-9a-f]{6}$'
    and jsonb_typeof(p_theme -> 'button') = 'string' and p_theme ->> 'button' ~ '^#[0-9a-f]{6}$'
    and jsonb_typeof(p_theme -> 'buttonStyle') = 'string' and p_theme ->> 'buttonStyle' in ('filled', 'outline', 'soft')
    and jsonb_typeof(p_theme -> 'corners') = 'string' and p_theme ->> 'corners' in ('square', 'rounded', 'pill')
    and jsonb_typeof(p_theme -> 'spacing') = 'string' and p_theme ->> 'spacing' in ('compact', 'regular', 'relaxed')
    and jsonb_typeof(p_theme -> 'font') = 'string' and p_theme ->> 'font' in ('system', 'serif', 'poppins', 'lora'),
    false);
$$;

-- Embed allowlist: a provider id and a resource id in the provider's own format. No URL, no markup.
create function private.is_valid_embed_ref(p_provider text, p_ref text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(case p_provider
    when 'youtube' then p_ref ~ '^[A-Za-z0-9_-]{11}$'
    when 'vimeo' then p_ref ~ '^[0-9]{6,12}$'
    when 'spotify' then p_ref ~ '^(?:track|album|playlist|episode|show|artist)/[A-Za-z0-9]{22}$'
  end, false);
$$;

create function private.mod11_check_digit(p_digits text, p_weights integer[])
returns integer
language sql
immutable
set search_path = ''
as $$
  select case when s.rest < 2 then 0 else 11 - s.rest end
  from (
    select sum(substr(p_digits, i, 1)::integer * p_weights[i]) % 11 as rest
    from generate_subscripts(p_weights, 1) i
  ) s;
$$;

-- Pix keys in their stored (normalized) form: CPF/CNPJ digits with valid check digits, "+55" phone,
-- lowercase e-mail up to 77 characters, or a random key (UUID).
create function private.is_valid_pix_key(p_type text, p_key text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(case p_type
    when 'cpf' then
      case when p_key ~ '^[0-9]{11}$' and p_key !~ '^([0-9])\1{10}$' then
        private.mod11_check_digit(p_key, array[10, 9, 8, 7, 6, 5, 4, 3, 2]) = substr(p_key, 10, 1)::integer
        and private.mod11_check_digit(p_key, array[11, 10, 9, 8, 7, 6, 5, 4, 3, 2]) = substr(p_key, 11, 1)::integer
      else false end
    when 'cnpj' then
      case when p_key ~ '^[0-9]{14}$' and p_key !~ '^([0-9])\1{13}$' then
        private.mod11_check_digit(p_key, array[5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]) = substr(p_key, 13, 1)::integer
        and private.mod11_check_digit(p_key, array[6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]) = substr(p_key, 14, 1)::integer
      else false end
    when 'phone' then p_key ~ '^\+55[1-9][0-9]{9,10}$'
    when 'email' then char_length(p_key) <= 77
      and p_key ~ '^[a-z0-9._%+-]+@(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$'
    when 'random' then p_key ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  end, false);
$$;

-- 1 to 4 distinct fields from the catalog, in catalog order, with e-mail or phone.
create function private.is_valid_form_fields(p_fields jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    jsonb_typeof(p_fields) = 'array'
    and jsonb_array_length(p_fields) between 1 and 4
    and not exists (
      select 1 from jsonb_array_elements(p_fields) e
      where jsonb_typeof(e) <> 'string' or (e #>> '{}') not in ('name', 'email', 'phone', 'message')
    )
    and (select array_agg(e #>> '{}' order by ord) from jsonb_array_elements(p_fields) with ordinality t(e, ord))
      = (select array_agg(f order by pos) from unnest(array['name', 'email', 'phone', 'message']) with ordinality c(f, pos) where p_fields ? f)
    and (p_fields ? 'email' or p_fields ? 'phone'),
    false);
$$;

-- A ready asset of the given kind that belongs to this page. When dimensions are given they must
-- be the asset's own, so a block cannot lie about the space an image takes.
create function private.is_ready_media(p_profile_id uuid, p_kind public.media_kind, p_media_id text, p_width jsonb, p_height jsonb)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.media_assets m
    where m.profile_id = p_profile_id
      and m.id::text = p_media_id
      and m.kind = p_kind
      and m.status = 'ready'
      and (p_width is null or (to_jsonb(m.width) = p_width and to_jsonb(m.height) = p_height))
  );
$$;

-- ---------------------------------------------------------------------------------------------
-- Draft validator (adds theme, avatar and the four block types to the Sprint 4 version)
-- ---------------------------------------------------------------------------------------------

create or replace function private.validate_profile_draft()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_keys text[];
  v_expected text[];
  v_type text;
  v_valid boolean;
begin
  -- Legacy page-level social links (no longer written by the app, still validated).
  if not private.is_valid_social_links(new.social_links) then
    raise exception 'invalid social link' using errcode = 'LK040', detail = 'social_links';
  end if;

  if new.theme is not null and not private.is_valid_theme(new.theme) then
    raise exception 'invalid theme' using errcode = 'LK040', detail = 'theme';
  end if;

  if new.avatar_path is not null and not private.is_ready_media(new.id, 'avatar', new.avatar_path, null, null) then
    raise exception 'invalid avatar' using errcode = 'LK040', detail = 'avatar_path';
  end if;

  -- Serialized size cap (MAX_BLOCKS_BYTES); the 100-block cap is the profiles_blocks_shape check.
  if octet_length(new.blocks::text) > 65536 then
    raise exception 'draft too large' using errcode = 'LK040', detail = 'blocks';
  end if;

  for v_item in select value from jsonb_array_elements(new.blocks) loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'invalid block' using errcode = 'LK040', detail = 'blocks';
    end if;
    v_type := case when jsonb_typeof(v_item -> 'type') = 'string' then v_item ->> 'type' end;
    v_expected := case v_type
      when 'link' then array['id', 'title', 'type', 'url', 'visible']
      when 'text' then array['id', 'text', 'type', 'visible']
      when 'social' then array['id', 'items', 'type', 'visible']
      when 'whatsapp' then array['id', 'label', 'message', 'phone', 'type', 'visible']
      when 'divider' then array['id', 'type', 'visible']
      when 'image' then array['alt', 'decorative', 'height', 'id', 'mediaId', 'type', 'visible', 'width']
      when 'embed' then array['id', 'provider', 'ref', 'title', 'type', 'visible']
      when 'pix' then array['id', 'key', 'keyType', 'label', 'paymentUrl', 'type', 'visible']
      when 'form' then array['buttonLabel', 'consentRequired', 'consentText', 'fields', 'id', 'title', 'type', 'visible']
    end;
    select array_agg(k order by k collate "C") into v_keys from jsonb_object_keys(v_item) k;
    if v_expected is null
      or v_keys is distinct from v_expected
      or jsonb_typeof(v_item -> 'id') <> 'string'
      or (v_item ->> 'id') !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      or jsonb_typeof(v_item -> 'visible') <> 'boolean' then
      raise exception 'invalid block' using errcode = 'LK040', detail = 'blocks';
    end if;

    v_valid := case v_type
      when 'link' then
        jsonb_typeof(v_item -> 'title') = 'string'
        and jsonb_typeof(v_item -> 'url') = 'string'
        and private.is_valid_block_label(v_item ->> 'title', 80)
        and private.is_allowed_block_url(v_item ->> 'url')
      when 'text' then
        jsonb_typeof(v_item -> 'text') = 'string'
        and private.is_valid_block_text(v_item ->> 'text', 1, 1000)
      when 'social' then
        private.is_valid_social_links(v_item -> 'items')
      when 'whatsapp' then
        jsonb_typeof(v_item -> 'label') = 'string'
        and jsonb_typeof(v_item -> 'phone') = 'string'
        and jsonb_typeof(v_item -> 'message') = 'string'
        and private.is_valid_block_label(v_item ->> 'label', 80)
        and private.is_valid_whatsapp_phone(v_item ->> 'phone')
        and private.is_valid_block_text(v_item ->> 'message', 0, 500)
      when 'divider' then true
      when 'image' then
        jsonb_typeof(v_item -> 'mediaId') = 'string'
        and jsonb_typeof(v_item -> 'width') = 'number'
        and jsonb_typeof(v_item -> 'height') = 'number'
        and jsonb_typeof(v_item -> 'alt') = 'string'
        and jsonb_typeof(v_item -> 'decorative') = 'boolean'
        and case when v_item -> 'decorative' = 'true'::jsonb
          then v_item ->> 'alt' = ''
          else private.is_valid_block_label(v_item ->> 'alt', 200) end
        -- Same page, ready, an image, and the block's dimensions are the asset's.
        and private.is_ready_media(new.id, 'image', v_item ->> 'mediaId', v_item -> 'width', v_item -> 'height')
      when 'embed' then
        jsonb_typeof(v_item -> 'provider') = 'string'
        and jsonb_typeof(v_item -> 'ref') = 'string'
        and jsonb_typeof(v_item -> 'title') = 'string'
        and private.is_valid_embed_ref(v_item ->> 'provider', v_item ->> 'ref')
        and private.is_valid_block_label(v_item ->> 'title', 80)
      when 'pix' then
        jsonb_typeof(v_item -> 'label') = 'string'
        and jsonb_typeof(v_item -> 'keyType') = 'string'
        and jsonb_typeof(v_item -> 'key') = 'string'
        and jsonb_typeof(v_item -> 'paymentUrl') = 'string'
        and private.is_valid_block_label(v_item ->> 'label', 80)
        and private.is_valid_pix_key(v_item ->> 'keyType', v_item ->> 'key')
        and (v_item ->> 'paymentUrl' = ''
          or (v_item ->> 'paymentUrl' ~ '^https://' and private.is_allowed_block_url(v_item ->> 'paymentUrl')))
      when 'form' then
        jsonb_typeof(v_item -> 'title') = 'string'
        and jsonb_typeof(v_item -> 'buttonLabel') = 'string'
        and jsonb_typeof(v_item -> 'consentText') = 'string'
        and jsonb_typeof(v_item -> 'consentRequired') = 'boolean'
        and private.is_valid_block_label(v_item ->> 'title', 80)
        and private.is_valid_block_label(v_item ->> 'buttonLabel', 40)
        and private.is_valid_block_label(v_item ->> 'consentText', 300)
        and private.is_valid_form_fields(v_item -> 'fields')
    end;
    if not coalesce(v_valid, false) then
      raise exception 'invalid block' using errcode = 'LK040', detail = 'blocks';
    end if;
  end loop;

  if (select count(*) from jsonb_array_elements(new.blocks))
    <> (select count(distinct e ->> 'id') from jsonb_array_elements(new.blocks) e) then
    raise exception 'duplicate block id' using errcode = 'LK040', detail = 'blocks';
  end if;

  return new;
end;
$$;

