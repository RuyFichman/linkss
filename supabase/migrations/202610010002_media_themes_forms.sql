create type public.media_kind as enum ('avatar', 'image');
create type public.media_status as enum ('pending', 'ready', 'failed', 'deleting');

create table public.media_assets (
  -- Also the storage key prefix: objects are "<id>/<width>.webp". Random, generated by the server.
  id uuid primary key,
  -- Restrict, not cascade: a workspace or page cannot be purged while it still owns objects.
  workspace_id uuid not null references public.workspaces (id) on delete restrict,
  profile_id uuid not null references public.profiles (id) on delete restrict,
  kind public.media_kind not null,
  status public.media_status not null default 'pending',
  -- Dimensions of the master (largest) variant.
  width integer not null check (width between 1 and 4096),
  height integer not null check (height between 1 and 4096),
  -- Sum of all variants.
  bytes integer not null check (bytes between 1 and 8388608),
  content_type text not null default 'image/webp' check (content_type = 'image/webp'),
  -- [{w, h, bytes}], validated by private.media_variants_are_valid.
  variants jsonb not null check (jsonb_typeof(variants) = 'array' and jsonb_array_length(variants) between 1 and 4),
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  constraint media_assets_ready_is_activated check (status <> 'ready' or activated_at is not null)
);

create index media_assets_workspace_idx on public.media_assets (workspace_id);
create index media_assets_profile_idx on public.media_assets (profile_id);
create index media_assets_created_by_idx on public.media_assets (created_by) where created_by is not null;
-- Cleanup scans by state and age.
create index media_assets_status_created_idx on public.media_assets (status, created_at);

