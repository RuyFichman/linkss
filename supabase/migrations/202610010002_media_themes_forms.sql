-- The only way a user token can write to storage: the object is a variant of a pending asset that
-- the same person registered (which needed the application's signature). A direct upload with a
-- valid session but no registration matches nothing and is rejected. There is no update or delete
-- policy; cleanup runs with the service role.
create policy media_objects_insert_registered on storage.objects
for insert to authenticated
with check (
  bucket_id = 'media'
  and exists (
    select 1
    from public.media_assets m
    where m.status = 'pending'
      and m.created_by = (select auth.uid())
      and objects.name in (
        select m.id::text || '/' || (v ->> 'w') || '.webp' from jsonb_array_elements(m.variants) v
      )
  )
);

