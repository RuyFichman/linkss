-- Counts of raw events per day, dimension, key and type: the single definition used both to build
-- the daily aggregate and to read days that are not final yet.
create function private.analytics_counts(p_profile_id uuid, p_from date, p_to date)
returns table (
  workspace_id uuid,
  profile_id uuid,
  day date,
  dimension public.analytics_dimension,
  key text,
  event_type public.analytics_event_type,
  count integer
)
language sql
stable
security definer
set search_path = ''
as $$
  with e as materialized (
    select ev.workspace_id, ev.profile_id, ev.day, ev.event_type, ev.block_id, ev.source, ev.device, ev.country,
      ev.utm_source, ev.utm_medium, ev.utm_campaign
    from public.analytics_events ev
    where ev.day between p_from and p_to
      and (p_profile_id is null or ev.profile_id = p_profile_id)
  )
  select e.workspace_id, e.profile_id, e.day, 'total'::public.analytics_dimension, '', e.event_type, count(*)::integer
  from e group by e.workspace_id, e.profile_id, e.day, e.event_type
  union all
  select e.workspace_id, e.profile_id, e.day, 'block', e.block_id, e.event_type, count(*)::integer
  from e where e.block_id is not null group by e.workspace_id, e.profile_id, e.day, e.block_id, e.event_type
  union all
  select e.workspace_id, e.profile_id, e.day, 'source', e.source::text, e.event_type, count(*)::integer
  from e where e.event_type = 'page_view' and e.source is not null group by e.workspace_id, e.profile_id, e.day, e.source, e.event_type
  union all
  select e.workspace_id, e.profile_id, e.day, 'utm', e.utm_source || '|' || coalesce(e.utm_medium, '') || '|' || coalesce(e.utm_campaign, ''), e.event_type, count(*)::integer
  from e where e.event_type = 'page_view' and e.utm_source is not null
  group by e.workspace_id, e.profile_id, e.day, e.utm_source, e.utm_medium, e.utm_campaign, e.event_type
  union all
  select e.workspace_id, e.profile_id, e.day, 'device', e.device::text, e.event_type, count(*)::integer
  from e where e.event_type = 'page_view' and e.device is not null group by e.workspace_id, e.profile_id, e.day, e.device, e.event_type
  union all
  select e.workspace_id, e.profile_id, e.day, 'country', e.country, e.event_type, count(*)::integer
  from e where e.event_type = 'page_view' and e.country is not null group by e.workspace_id, e.profile_id, e.day, e.country, e.event_type;
$$;

-- Rebuilds the aggregate of one day from its raw events. Replacement, not accumulation: running it
-- again gives the same rows. A day before today becomes final.
create function private.aggregate_analytics_day(p_day date)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rows integer;
begin
  delete from public.analytics_daily d where d.day = p_day;
  insert into public.analytics_daily (workspace_id, profile_id, day, dimension, key, event_type, count)
  select c.workspace_id, c.profile_id, c.day, c.dimension, c.key, c.event_type, c.count
  from private.analytics_counts(null, p_day, p_day) c;
  get diagnostics v_rows = row_count;

  insert into public.analytics_day_status (day, aggregated_at, finalized_at, event_count)
  values (p_day, now(), case when p_day < private.analytics_today() then now() end,
    (select count(*) from public.analytics_events e where e.day = p_day))
  on conflict (day) do update
  set aggregated_at = excluded.aggregated_at,
    event_count = excluded.event_count,
    finalized_at = coalesce(public.analytics_day_status.finalized_at, excluded.finalized_at);
  return v_rows;
end;
$$;

-- The scheduled job (service role only). Aggregates every day that is not final yet, up to today
-- (at most 10 days per run), then deletes raw events older than the retention for days that are
-- final (at most 50,000 rows per run) and aggregates past their own retention. Safe to repeat.
-- With `p_day`, only re-aggregates that day, which must still have its raw events.
create function public.run_analytics_maintenance(p_day date default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_today date := private.analytics_today();
  v_raw_floor date := v_today - private.analytics_raw_retention_days();
  v_start date;
  v_day date;
  v_days integer := 0;
  v_rows integer := 0;
  v_purged_events integer := 0;
  v_purged_aggregates integer := 0;
begin
  -- One run at a time.
  perform pg_advisory_xact_lock(hashtextextended('analytics:maintenance', 0));

  if p_day is not null then
    if p_day > v_today or p_day < v_raw_floor then
      return jsonb_build_object('status', 'out_of_range', 'today', v_today, 'oldest_raw_day', v_raw_floor);
    end if;
    v_rows := private.aggregate_analytics_day(p_day);
    return jsonb_build_object('status', 'ok', 'aggregated_days', 1, 'aggregate_rows', v_rows, 'purged_events', 0,
      'purged_aggregate_rows', 0, 'pending_days', 0,
      'last_final_day', (select max(s.day) from public.analytics_day_status s where s.finalized_at is not null));
  end if;

  -- First day that is not final: the day after the watermark, or the first day that has events.
  select coalesce(
    (select max(s.day) + 1 from public.analytics_day_status s where s.finalized_at is not null),
    (select min(e.day) from public.analytics_events e),
    v_today) into v_start;

  v_day := v_start;
  while v_day <= v_today and v_days < 10 loop
    v_rows := v_rows + private.aggregate_analytics_day(v_day);
    v_days := v_days + 1;
    v_day := v_day + 1;
  end loop;

  -- Raw events are deleted only after their day is final, so a job that was down loses nothing.
  delete from public.analytics_events e
  where e.ctid in (
    select ev.ctid
    from public.analytics_events ev
    join public.analytics_day_status s on s.day = ev.day and s.finalized_at is not null
    where ev.day < v_raw_floor
    limit 50000);
  get diagnostics v_purged_events = row_count;

  delete from public.analytics_daily d where d.day < v_today - private.analytics_aggregate_retention_days();
  get diagnostics v_purged_aggregates = row_count;
  delete from public.analytics_day_status s where s.day < v_today - private.analytics_aggregate_retention_days();

  return jsonb_build_object('status', 'ok', 'aggregated_days', v_days, 'aggregate_rows', v_rows,
    'purged_events', v_purged_events, 'purged_aggregate_rows', v_purged_aggregates,
    -- Days still waiting because of the per-run bound; the next run continues.
    'pending_days', greatest(0, v_today - v_day + 1),
    'last_final_day', (select max(s.day) from public.analytics_day_status s where s.finalized_at is not null));
end;
$$;

