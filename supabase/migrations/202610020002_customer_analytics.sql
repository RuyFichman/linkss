-- ---------------------------------------------------------------------------------------------
-- Ingestion (the only write path for visitors)
-- ---------------------------------------------------------------------------------------------

-- Stores a batch of events for one published page. `p_payload` is the JSON text built by the
-- application server (modules/analytics/attestation.ts) and `p_signature` its HMAC-SHA256:
--   {"v":1,"slug":"…","visitor":"<32 hex>"|null,
--    "view":{"source":"…","device":"…","country":"BR","utm_source":…,"utm_medium":…,"utm_campaign":…},
--    "events":[{"id":"<uuid>","type":"link_click","block":"<block id>"|null}]}
-- Answers {"status": …} and, for "ok", how many events were accepted, were duplicates of stored
-- events, were repeat views inside the visit window, were rejected or were rate limited. Safe to
-- retry: an event id is stored once per page.
--   not_configured  the signing secret is not in Vault
--   forbidden       missing or wrong signature (a direct call without the server)
--   invalid         malformed payload
--   unsupported     contract version this database does not know
--   unavailable     no published page at this address
create function public.ingest_analytics_events(p_payload text, p_signature text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_valid boolean;
  v_payload jsonb;
  v_slug text;
  v_profile public.profiles;
  v_document jsonb;
  v_blocks jsonb;
  v_view jsonb;
  v_visitor text;
  v_source public.analytics_source;
  v_device public.analytics_device;
  v_country text;
  v_utm_source text;
  v_utm_medium text;
  v_utm_campaign text;
  v_keep_utm boolean;
  v_event jsonb;
  v_type public.analytics_event_type;
  v_expected text;
  v_block text;
  v_day date;
  v_page_count integer;
  v_visitor_count integer;
  v_rows integer;
  v_accepted integer := 0;
  v_duplicate integer := 0;
  v_repeat integer := 0;
  v_rejected integer := 0;
  v_limited integer := 0;
begin
  if p_payload is null or octet_length(p_payload) > 8192 then
    return jsonb_build_object('status', 'invalid');
  end if;
  -- Before anything else: an unsigned caller learns nothing about pages or payloads.
  v_valid := private.analytics_signature_is_valid(p_payload, p_signature);
  if v_valid is null then
    return jsonb_build_object('status', 'not_configured');
  end if;
  if not v_valid then
    return jsonb_build_object('status', 'forbidden');
  end if;

  begin
    v_payload := p_payload::jsonb;
  exception when others then
    return jsonb_build_object('status', 'invalid');
  end;
  if jsonb_typeof(v_payload) <> 'object' then
    return jsonb_build_object('status', 'invalid');
  end if;
  if v_payload -> 'v' is distinct from '1'::jsonb then
    return jsonb_build_object('status', 'unsupported');
  end if;
  if jsonb_typeof(v_payload -> 'slug') is distinct from 'string'
    or jsonb_typeof(v_payload -> 'events') is distinct from 'array'
    or jsonb_array_length(v_payload -> 'events') not between 1 and 10 then
    return jsonb_build_object('status', 'invalid');
  end if;
  v_slug := v_payload ->> 'slug';
  if not private.slug_is_well_formed(v_slug) then
    return jsonb_build_object('status', 'unavailable');
  end if;

  -- Published, not deleted, in an active workspace: the same rule as submit_form_lead.
  select p.* into v_profile
  from public.profiles p
  join public.workspaces w on w.id = p.workspace_id
  where p.slug = v_slug
    and p.deleted_at is null
    and p.live_publication_id is not null
    and w.deleted_at is null
    and w.status = 'active';
  if not found then
    return jsonb_build_object('status', 'unavailable');
  end if;

  -- Blocks of the LIVE publication: {id: type}. An event can only name one of these.
  select pp.document into v_document from public.profile_publications pp where pp.id = v_profile.live_publication_id;
  select coalesce(jsonb_object_agg(b ->> 'id', b ->> 'type'), '{}'::jsonb) into v_blocks
  from jsonb_array_elements(case when jsonb_typeof(v_document -> 'blocks') = 'array' then v_document -> 'blocks' else '[]'::jsonb end) b
  where jsonb_typeof(b -> 'id') = 'string' and jsonb_typeof(b -> 'type') = 'string';
  -- A schema-version-1 snapshot shows its page-level social links as one row with a fixed id.
  if v_document ->> 'schemaVersion' = '1'
    and jsonb_typeof(v_document -> 'socialLinks') = 'array'
    and jsonb_array_length(v_document -> 'socialLinks') > 0 then
    v_blocks := v_blocks || jsonb_build_object('legacy-social', 'social');
  end if;

  v_visitor := case when jsonb_typeof(v_payload -> 'visitor') = 'string' and v_payload ->> 'visitor' ~ '^[0-9a-f]{32}$' then v_payload ->> 'visitor' end;

  v_view := case when jsonb_typeof(v_payload -> 'view') = 'object' then v_payload -> 'view' else '{}'::jsonb end;
  v_source := case when v_view ->> 'source' = any (enum_range(null::public.analytics_source)::text[]) then (v_view ->> 'source')::public.analytics_source end;
  v_device := case when v_view ->> 'device' = any (enum_range(null::public.analytics_device)::text[]) then (v_view ->> 'device')::public.analytics_device end;
  v_country := case when v_view ->> 'country' ~ '^[A-Z]{2}$' then v_view ->> 'country' else 'ZZ' end;
  v_utm_source := case when private.analytics_utm_is_valid(v_view ->> 'utm_source') then v_view ->> 'utm_source' end;
  if v_utm_source is not null then
    v_utm_medium := case when private.analytics_utm_is_valid(v_view ->> 'utm_medium') then v_view ->> 'utm_medium' end;
    v_utm_campaign := case when private.analytics_utm_is_valid(v_view ->> 'utm_campaign') then v_view ->> 'utm_campaign' end;
  end if;

  v_day := private.analytics_today();

  -- One batch at a time per page, so the counters below cannot be raced.
  perform pg_advisory_xact_lock(hashtextextended('analytics:' || v_profile.id::text, 0));

  -- Stored events only: what was rejected never counts against anybody.
  select count(*) into v_page_count
  from public.analytics_events e
  where e.workspace_id = v_profile.workspace_id and e.profile_id = v_profile.id
    and e.occurred_at > now() - interval '1 hour';
  -- Requests without a hash share one bucket per page. Server-side form events are not a visitor's.
  select count(*) into v_visitor_count
  from public.analytics_events e
  where e.workspace_id = v_profile.workspace_id and e.profile_id = v_profile.id
    and e.occurred_at > now() - interval '10 minutes'
    and e.visitor_hash is not distinct from v_visitor
    and e.event_type <> 'form_submit';

  for v_event in select value from jsonb_array_elements(v_payload -> 'events') loop
    -- form_submit is recorded by submit_form_lead when a lead is stored; nobody can send it.
    if jsonb_typeof(v_event) <> 'object'
      or jsonb_typeof(v_event -> 'id') is distinct from 'string'
      or (v_event ->> 'id') !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      or jsonb_typeof(v_event -> 'type') is distinct from 'string'
      or not (v_event ->> 'type' = any (enum_range(null::public.analytics_event_type)::text[]))
      or v_event ->> 'type' = 'form_submit' then
      v_rejected := v_rejected + 1;
      continue;
    end if;
    v_type := (v_event ->> 'type')::public.analytics_event_type;
    v_expected := private.analytics_event_block_type(v_type);
    v_block := case when jsonb_typeof(v_event -> 'block') = 'string' then v_event ->> 'block' end;

    if (v_expected is null and coalesce(jsonb_typeof(v_event -> 'block'), 'null') <> 'null')
      -- The block must be in the live publication and be of the type this event belongs to.
      or (v_expected is not null and (v_block is null or v_blocks ->> v_block is distinct from v_expected))
      or (v_type = 'page_view' and (v_source is null or v_device is null)) then
      v_rejected := v_rejected + 1;
      continue;
    end if;

    if exists (select 1 from public.analytics_events e where e.profile_id = v_profile.id and e.event_id = (v_event ->> 'id')::uuid) then
      v_duplicate := v_duplicate + 1;
      continue;
    end if;

    if v_page_count >= 2000 or v_visitor_count >= 30 then
      v_limited := v_limited + 1;
      continue;
    end if;

    -- Visit rule: a view from the same visitor within 30 minutes of a stored view is not a new visit.
    if v_type = 'page_view' and v_visitor is not null and exists (
      select 1 from public.analytics_events e
      where e.workspace_id = v_profile.workspace_id and e.profile_id = v_profile.id
        and e.occurred_at > now() - interval '30 minutes'
        and e.event_type = 'page_view' and e.visitor_hash = v_visitor
    ) then
      v_repeat := v_repeat + 1;
      continue;
    end if;

    -- Cardinality cap: at most 20 distinct UTM triples per page per day. Beyond that the view is
    -- still counted, without its UTM values.
    v_keep_utm := v_type = 'page_view' and v_utm_source is not null;
    if v_keep_utm and not exists (
      select 1 from public.analytics_events e
      where e.workspace_id = v_profile.workspace_id and e.profile_id = v_profile.id
        and e.occurred_at >= private.analytics_day_start(v_day)
        and e.utm_source = v_utm_source
        and e.utm_medium is not distinct from v_utm_medium
        and e.utm_campaign is not distinct from v_utm_campaign
    ) and (
      select count(*) from (
        select distinct e.utm_source, e.utm_medium, e.utm_campaign
        from public.analytics_events e
        where e.workspace_id = v_profile.workspace_id and e.profile_id = v_profile.id
          and e.occurred_at >= private.analytics_day_start(v_day)
          and e.utm_source is not null
      ) t
    ) >= 20 then
      v_keep_utm := false;
    end if;

    insert into public.analytics_events (
      profile_id, event_id, workspace_id, occurred_at, day, event_type, source, device, country, block_id, visitor_hash,
      utm_source, utm_medium, utm_campaign)
    values (
      v_profile.id, (v_event ->> 'id')::uuid, v_profile.workspace_id, now(), v_day, v_type,
      case when v_type = 'page_view' then v_source end,
      case when v_type = 'page_view' then v_device end,
      case when v_type = 'page_view' then v_country end,
      v_block, v_visitor,
      case when v_keep_utm then v_utm_source end,
      case when v_keep_utm then v_utm_medium end,
      case when v_keep_utm then v_utm_campaign end)
    on conflict (profile_id, event_id) do nothing;
    get diagnostics v_rows = row_count;
    if v_rows = 0 then
      v_duplicate := v_duplicate + 1;
    else
      v_accepted := v_accepted + 1;
      v_page_count := v_page_count + 1;
      v_visitor_count := v_visitor_count + 1;
    end if;
  end loop;

  return jsonb_build_object('status', 'ok', 'accepted', v_accepted, 'duplicate', v_duplicate, 'repeat', v_repeat,
    'rejected', v_rejected, 'rate_limited', v_limited);
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Form submission: the event is recorded where the lead is stored
-- ---------------------------------------------------------------------------------------------

-- Same function as Sprint 5 (signature, validation, limits and answers unchanged) plus one step:
-- when a lead is actually stored, a form_submit event is recorded in the same transaction. A retry
-- that is stored once produces one event. An analytics failure never fails the lead.
create or replace function public.submit_form_lead(
  p_slug text,
  p_block_id text,
  p_fields jsonb,
  p_consent boolean default false,
  p_honeypot text default '',
  p_client_hash text default null
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_slug text := private.normalize_slug(coalesce(p_slug, ''));
  v_profile public.profiles;
  v_document jsonb;
  v_version integer;
  v_form jsonb;
  v_field text;
  v_value text;
  v_name text;
  v_email text;
  v_phone text;
  v_message text;
  v_consent boolean := coalesce(p_consent, false);
  v_client text;
  v_dedupe text;
begin
  -- Hidden field real visitors never fill. Automated posts get the same answer as a real one.
  if btrim(coalesce(p_honeypot, '')) <> '' then
    return 'ok';
  end if;
  if not private.slug_is_well_formed(v_slug) or p_block_id is null then
    return 'unavailable';
  end if;
  if p_fields is null or jsonb_typeof(p_fields) <> 'object' or octet_length(p_fields::text) > 4096 then
    return 'invalid';
  end if;

  select p.* into v_profile
  from public.profiles p
  join public.workspaces w on w.id = p.workspace_id
  where p.slug = v_slug
    and p.deleted_at is null
    and p.live_publication_id is not null
    and w.deleted_at is null
    and w.status = 'active';
  if not found then
    return 'unavailable';
  end if;

  select pp.document, pp.version into v_document, v_version
  from public.profile_publications pp where pp.id = v_profile.live_publication_id;
  select b into v_form
  from jsonb_array_elements(case when jsonb_typeof(v_document -> 'blocks') = 'array' then v_document -> 'blocks' else '[]'::jsonb end) b
  where b ->> 'id' = p_block_id and b ->> 'type' = 'form'
  limit 1;
  if v_form is null or not private.is_valid_form_fields(v_form -> 'fields') then
    return 'unavailable';
  end if;

  -- Only the fields of the published form are read; anything else in the request is ignored.
  for v_field in select f from unnest(array['name', 'email', 'phone', 'message']) f where v_form -> 'fields' ? f loop
    v_value := case when jsonb_typeof(p_fields -> v_field) = 'string' then p_fields ->> v_field else '' end;
    if v_field = 'message' then
      v_value := btrim(regexp_replace(v_value, E'\r\n?', E'\n', 'g'), E' \t\n');
      if char_length(v_value) > 1000 or replace(v_value, E'\n', '') ~ '[[:cntrl:]]' then
        return 'invalid';
      end if;
      v_message := nullif(v_value, '');
    else
      v_value := regexp_replace(btrim(v_value, E' \t\n\r'), '\s+', ' ', 'g');
      if v_value = '' or v_value ~ '[[:cntrl:]]' then
        return 'invalid';
      end if;
      if v_field = 'name' then
        if char_length(v_value) > 100 then return 'invalid'; end if;
        v_name := v_value;
      elsif v_field = 'email' then
        v_value := lower(v_value);
        if char_length(v_value) > 254 or v_value !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then return 'invalid'; end if;
        v_email := v_value;
      else
        if char_length(v_value) > 20 or v_value !~ '^\+?[0-9[:space:]().-]+$' then return 'invalid'; end if;
        v_phone := case when v_value like '+%' then '+' else '' end || regexp_replace(v_value, '[^0-9]', '', 'g');
        if v_phone !~ '^\+?[0-9]{8,15}$' then return 'invalid'; end if;
      end if;
    end if;
  end loop;

  if coalesce((v_form ->> 'consentRequired')::boolean, true) and not v_consent then
    return 'consent_required';
  end if;

  -- One submission at a time per page, so the counters below cannot be raced.
  perform pg_advisory_xact_lock(hashtextextended('form_lead:' || v_profile.id::text, 0));

  delete from public.form_submission_hits h where h.profile_id = v_profile.id and h.created_at < now() - interval '1 day';
  delete from public.form_leads l where l.profile_id = v_profile.id and l.purge_after < now();

  -- Retry safety: the same content to the same form within 10 minutes is stored once.
  v_dedupe := md5(v_profile.id::text || ':' || p_block_id || ':' || coalesce(v_name, '') || E'\x1f' || coalesce(v_email, '') || E'\x1f' || coalesce(v_phone, '') || E'\x1f' || coalesce(v_message, ''));
  if exists (
    select 1 from public.form_leads l
    where l.profile_id = v_profile.id and l.dedupe_key = v_dedupe and l.created_at > now() - interval '10 minutes'
  ) then
    return 'ok';
  end if;

  -- A caller without a hash from the application (a direct API call) shares one bucket.
  v_client := case when p_client_hash ~ '^[0-9a-f]{32}$' then p_client_hash else 'direct' end;
  if (select count(*) from public.form_submission_hits h
      where h.profile_id = v_profile.id and h.client_hash = v_client and h.created_at > now() - interval '10 minutes') >= 5
    or (select count(*) from public.form_submission_hits h
        where h.profile_id = v_profile.id and h.created_at > now() - interval '1 hour') >= 60 then
    return 'rate_limited';
  end if;

  insert into public.form_submission_hits (profile_id, client_hash) values (v_profile.id, v_client);
  insert into public.form_leads (
    workspace_id, profile_id, block_id, publication_version, name, email, phone, message,
    consent_given, consent_required, consent_text, consent_version, consented_at, dedupe_key, purge_after)
  values (
    v_profile.workspace_id, v_profile.id, p_block_id, v_version, v_name, v_email, v_phone, v_message,
    v_consent, coalesce((v_form ->> 'consentRequired')::boolean, true), v_form ->> 'consentText', md5(v_form ->> 'consentText'),
    case when v_consent then now() end, v_dedupe, now() + private.lead_retention());

  -- Customer analytics (ADR 0011): the one place a form_submit event is created. It carries no
  -- visitor hash and nothing of what was typed. Never allowed to fail the lead.
  begin
    insert into public.analytics_events (profile_id, event_id, workspace_id, occurred_at, day, event_type, block_id)
    values (v_profile.id, gen_random_uuid(), v_profile.workspace_id, now(), private.analytics_today(), 'form_submit', p_block_id);
  exception when others then
    null;
  end;
  return 'ok';
end;
$$;

