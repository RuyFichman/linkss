-- Shared secret between the application server (ANALYTICS_SIGNING_SECRET) and the database. Stored
-- in Supabase Vault under this name by a deploy step, never in a migration.
create function private.analytics_signing_secret()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select s.decrypted_secret from vault.decrypted_secrets s where s.name = 'analytics_signing_secret' limit 1;
$$;

create function private.analytics_is_configured()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$ select coalesce(char_length(private.analytics_signing_secret()) >= 32, false) $$;

-- True/false for a configured database; null when the secret is missing (nothing can be attested).
create function private.analytics_signature_is_valid(p_payload text, p_signature text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_secret text := private.analytics_signing_secret();
  v_expected text;
begin
  if v_secret is null or char_length(v_secret) < 32 then
    return null;
  end if;
  if p_payload is null or p_signature is null or p_signature !~ '^[0-9a-f]{64}$' then
    return false;
  end if;
  v_expected := encode(extensions.hmac(convert_to(p_payload, 'UTF8'), convert_to(v_secret, 'UTF8'), 'sha256'), 'hex');
  -- Compare digests so the time taken does not depend on where the two strings differ.
  return extensions.digest(v_expected, 'sha256') = extensions.digest(p_signature, 'sha256');
end;
$$;

-- Block type an event must point at; null for page-level events (mirror of EVENT_BLOCK_TYPE).
create function private.analytics_event_block_type(p_type public.analytics_event_type)
