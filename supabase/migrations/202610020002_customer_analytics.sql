-- ---------------------------------------------------------------------------------------------
-- Raw events (append-only, short-lived)
-- ---------------------------------------------------------------------------------------------

create table public.analytics_events (
  profile_id uuid not null references public.profiles (id) on delete cascade,
  -- Generated by the visitor's browser (or by the database for form_submit); the deduplication key.
  event_id uuid not null,
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  -- Server clock at arrival. The client's clock is never trusted.
  occurred_at timestamptz not null default now(),
  -- Reporting day of occurred_at (private.analytics_local_day).
  day date not null,
  event_type public.analytics_event_type not null,
  -- Page-view dimensions: how the visit arrived. Null on every other event type.
  source public.analytics_source,
  device public.analytics_device,
  country text check (country is null or country ~ '^[A-Z]{2}$'),
  -- Id of the block in the live publication; null for page-level events.
  block_id text check (block_id is null or char_length(block_id) between 1 and 64),
  -- Salted daily HMAC of page + address + user agent; never the address. Null when the server has no salt.
  visitor_hash text check (visitor_hash is null or visitor_hash ~ '^[0-9a-f]{32}$'),
  utm_source text check (utm_source is null or utm_source ~ '^[a-z0-9_.-]{1,40}$'),
  utm_medium text check (utm_medium is null or utm_medium ~ '^[a-z0-9_.-]{1,40}$'),
  utm_campaign text check (utm_campaign is null or utm_campaign ~ '^[a-z0-9_.-]{1,40}$'),
  -- Also serves the page foreign key and deduplication (ignored on conflict).
  primary key (profile_id, event_id),
  constraint analytics_events_view_dimensions check (
    event_type = 'page_view'
    or (source is null and device is null and country is null and utm_source is null)
  ),
  constraint analytics_events_utm_needs_source check (
    utm_source is not null or (utm_medium is null and utm_campaign is null)
  )
);

-- Rate limits, the visit rule and the workspace foreign key.
create index analytics_events_workspace_profile_time_idx on public.analytics_events (workspace_id, profile_id, occurred_at);
-- Aggregation and purge go day by day.
create index analytics_events_day_idx on public.analytics_events (day);

comment on table public.analytics_events is
  'Raw customer-analytics events (ADR 0011). Append-only, written only by ingest_analytics_events and submit_form_lead, kept for private.analytics_raw_retention_days() days and then deleted by run_analytics_maintenance. Holds no IP address, user agent, referrer or URL: only enumerations, a salted daily hash and normalized UTM values. No client role can read it.';

